  private SubtitleCatalog() {}
  private static void caption(String key, String label) { CAPTIONS.put(key, new Caption(key, label)); }
  public static Collection<Caption> captions() { return Collections.unmodifiableCollection(CAPTIONS.values()); }
  public static Caption caption(String key) { return CAPTIONS.get(key); }
  public static Caption resolve(String sound, String context) {
    if (!SOUNDS.containsKey(sound)) return null;
    if (context == null) return SOUNDS.get(sound);
    if (context.equals("hurt") || context.equals("death") || context.equals("player-hurt") || context.equals("player-death")) {
      String phase = context.endsWith("death") ? "death" : "hurt";
      String family = context.startsWith("player-") ? "player" : family(sound);
      return CAPTIONS.get("subtitles.entity." + family + "." + phase);
    }
    Caption override = CAPTIONS.get(context); return override != null ? override : SOUNDS.get(sound);
  }
  private static String family(String sound) {
    if (sound.startsWith("mob.zombiepig.")) return "zombified_piglin";
    for (String species : List.of("chicken", "cow", "creeper", "ghast", "pig", "sheep", "skeleton", "slime", "spider", "wolf", "zombie"))
      if (sound.startsWith("mob." + species)) return species;
    return "generic";
  }
